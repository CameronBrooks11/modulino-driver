//! Keeps `tests/readme_examples.rs` in step with the Rust blocks in
//! `README.md`. That file wraps each block in a function that is compiled
//! but never called, so `cargo test` fails when an example stops building.
//! This test fails when the file no longer matches the README; `just readme`
//! regenerates it.

use std::path::Path;

const GENERATED: &str = "tests/readme_examples.rs";

/// What every block may use without declaring it: mock buses and a delay.
const SETUP: &str = "    let mut i2c = Mock::new(&[]);
    let i2c_a = Mock::new(&[]);
    let i2c_b = Mock::new(&[]);
    let mut bus = Mock::new(&[]);
    let mut delay = NoopDelay::new();
";

/// The README's ```rust blocks, each with the nearest heading above it.
///
/// Only fences this function understands pass: an unindented ``` with
/// `rust`, `toml`, `sh`, `text` or no info string, closed by a bare ```.
/// Anything else panics, so a block is never skipped silently.
fn blocks(readme: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    let mut heading = String::new();
    let mut lines = readme.lines().enumerate();
    while let Some((n, line)) = lines.next() {
        let trimmed = line.trim();
        if trimmed.starts_with("~~~") || (trimmed.starts_with("```") && line != trimmed) {
            panic!("README.md:{}: unsupported fence {line:?}", n + 1);
        }
        if let Some(h) = line.strip_prefix('#') {
            heading = h.trim_start_matches('#').trim().to_string();
            continue;
        }
        let Some(lang) = line.strip_prefix("```") else {
            continue;
        };
        if !["rust", "toml", "sh", "text", ""].contains(&lang) {
            panic!(
                "README.md:{}: fence info {lang:?}; use plain ```rust or extend tests/readme_sync.rs",
                n + 1
            );
        }
        let mut body = String::new();
        let mut closed = false;
        for (m, line) in lines.by_ref() {
            if line.trim().starts_with("```") {
                if line != "```" {
                    panic!("README.md:{}: unsupported closing fence {line:?}", m + 1);
                }
                closed = true;
                break;
            }
            body.push_str(line);
            body.push('\n');
        }
        assert!(closed, "README.md:{}: fence never closed", n + 1);
        if lang == "rust" {
            out.push((heading.clone(), body));
        }
    }
    out
}

fn render(readme: &str) -> String {
    let mut out = String::from(
        "//! The Rust blocks in `README.md`, each wrapped in a function that is
//! compiled and never called. Generated by `just readme`; do not edit.
//! `tests/readme_sync.rs` fails when this file no longer matches the README.

#![allow(unused)]
#![deny(unused_must_use)]

use embedded_hal::i2c::ErrorKind;
use embedded_hal_mock::eh1::{delay::NoopDelay, i2c::Mock};
use modulino_driver::Error;
",
    );
    for (i, (heading, body)) in blocks(readme).iter().enumerate() {
        out.push_str(&format!(
            "\n// README.md: {heading}\n#[rustfmt::skip]\nfn block_{}() -> Result<(), Error<ErrorKind>> {{\n{SETUP}\n",
            i + 1
        ));
        for line in body.lines() {
            if line.is_empty() {
                out.push('\n');
            } else {
                out.push_str("    ");
                out.push_str(line);
                out.push('\n');
            }
        }
        out.push_str("    Ok(())\n}\n");
    }
    out
}

#[test]
fn readme_examples_match_the_readme() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let readme = std::fs::read_to_string(root.join("README.md")).unwrap();
    let expected = render(&readme);
    assert!(
        !blocks(&readme).is_empty(),
        "no ```rust blocks found in README.md"
    );
    let path = root.join(GENERATED);
    // Write mode only on exactly README_UPDATE=1, and never in CI, where a
    // rewrite would turn the drift check into a pass.
    if std::env::var("README_UPDATE").as_deref() == Ok("1") {
        assert!(
            std::env::var_os("CI").is_none(),
            "README_UPDATE=1 is for `just readme`, not CI"
        );
        std::fs::write(&path, &expected).unwrap();
        return;
    }
    // Git may check the file out with CRLF line endings on Windows.
    let actual = std::fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        actual == expected,
        "{GENERATED} does not match README.md; run `just readme`"
    );
}
